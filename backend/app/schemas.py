from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field, field_validator


class ObservedRange(BaseModel):
    min: float = 1.0
    max: float = 9.35


class PromptAnalysis(BaseModel):
    word_count: int
    char_count: int
    has_role_or_context: bool
    has_task_instruction: bool
    has_audience: bool
    has_format_specification: bool
    has_constraints: bool
    has_examples_request: bool
    structural_breadth: str


class PredictRequest(BaseModel):
    prompt: str = Field(
        ...,
        min_length=1,
        max_length=5000,
        description="User-submitted prompt string to evaluate."
    )

    @field_validator("prompt")
    @classmethod
    def validate_prompt_not_blank(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("Prompt cannot be empty or contain only whitespace.")
        return stripped


class PredictResponse(BaseModel):
    prompt: str
    predicted_score: float
    model: str = "BiLSTM"
    observed_dataset_range: ObservedRange = Field(default_factory=ObservedRange)
    is_within_observed_range: bool
    disclaimer: str = (
        "Model-estimated score, not an expert assessment. Numerical prediction is "
        "independently inferred by the trained BiLSTM model."
    )
    suggestions: List[str]
    analysis: PromptAnalysis
    suggested_template: Optional[str] = None


class CompareRequest(BaseModel):
    original_prompt: str = Field(..., min_length=1, max_length=5000)
    revised_prompt: str = Field(..., min_length=1, max_length=5000)

    @field_validator("original_prompt", "revised_prompt")
    @classmethod
    def validate_not_blank(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("Prompt cannot be empty or contain only whitespace.")
        return stripped


class CompareResponse(BaseModel):
    original_prompt: str
    original_score: float
    revised_prompt: str
    revised_score: float
    score_diff: float
    model: str = "BiLSTM"
    observed_dataset_range: ObservedRange = Field(default_factory=ObservedRange)
    disclaimer: str = (
        "Both scores are predicted independently by the same trained BiLSTM model. "
        "Suggestions are generated by an independent rule-based helper."
    )
    original_suggestions: List[str]
    revised_suggestions: List[str]
    original_analysis: PromptAnalysis
    revised_analysis: PromptAnalysis


class HealthResponse(BaseModel):
    status: str
    model_loaded: bool
    model_identifier: str = "BiLSTM (best_pels_bilstm_model.keras)"
    model_path: str
    detail: Optional[str] = None


class ModelArchitectureInfo(BaseModel):
    framework: str
    keras_format: str
    vocabulary_limit: int
    sequence_length: int
    embedding_dimension: int
    bilstm_units: int
    dropout_rate: float
    dense_output: int
    output_activation: str
    optimizer: str
    learning_rate: float
    loss_function: str
    batch_size: int
    max_epochs: int
    early_stopping_patience: int


class DatasetInfo(BaseModel):
    name: str
    source: str
    excel_filename: str
    worksheet: str
    total_raw_records: int
    unique_modeling_records: int
    training_samples: int
    validation_samples: int
    testing_samples: int
    input_feature: str
    target_column: str
    observed_score_min: float
    observed_score_max: float
    rubric_dimensions: List[str]


class ModelInfoResponse(BaseModel):
    model_name: str
    architecture_details: ModelArchitectureInfo
    dataset_details: DatasetInfo
    headline_metrics: Dict[str, float]
    architectural_flow: List[str]


class ModelComparisonRecord(BaseModel):
    model: str
    mae: float
    mse: float
    rmse: float
    r2: float
    rank_by_mae: int


class MetricsResponse(BaseModel):
    records: List[ModelComparisonRecord]
    best_model: str
    mae_reduction_vs_baseline_pct: float
    regression_notes: str
